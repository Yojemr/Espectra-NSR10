"""Extract NSR-10 Appendix A-4 and compare two independent PDF readers."""
import argparse
import hashlib
import json
import re
from pathlib import Path

from pypdf import PdfReader
import pdfplumber

DEPARTMENTS = {
    '05': 'Antioquia', '08': 'Atlántico', '11': 'Bogotá, D. C.',
    '13': 'Bolívar', '15': 'Boyacá', '17': 'Caldas', '18': 'Caquetá',
    '19': 'Cauca', '20': 'Cesar', '23': 'Córdoba', '25': 'Cundinamarca',
    '27': 'Chocó', '41': 'Huila', '44': 'La Guajira', '47': 'Magdalena',
    '50': 'Meta', '52': 'Nariño', '54': 'Norte de Santander', '63': 'Quindío',
    '66': 'Risaralda', '68': 'Santander', '70': 'Sucre', '73': 'Tolima',
    '76': 'Valle del Cauca', '81': 'Arauca', '85': 'Casanare', '86': 'Putumayo',
    '88': 'San Andrés, Providencia y Santa Catalina', '91': 'Amazonas',
    '94': 'Guainía', '95': 'Guaviare', '97': 'Vaupés', '99': 'Vichada',
}
ROW = re.compile(r'^(.+?)\s+(\d{5})\s+(0\.\d{2})\s+(0\.\d{2})\s+(Baja|Intermedia|Alta)\s+(0\.\d{2})\s+(0\.\d{2})\s*$')


def parse(text, pdf_page):
    result = []
    for raw in text.splitlines():
        line = re.sub(r'(?<=\d)\.\s+(?=\d)', '.', raw.strip())
        line = re.sub(r'\b(\d{3})\s+(\d{2})(?=\s+0\.)', r'\1\2', line)
        line = line.replace('In termedia', 'Intermedia')
        m = ROW.match(line)
        if m:
            name, code, aa, av, hazard, ae, ad = m.groups()
            result.append(dict(code=code, name=name.strip(), department=DEPARTMENTS[code[:2]],
                               aa=float(aa), av=float(av), hazard=hazard,
                               page=f'A-{pdf_page - 12}', pdfPage=pdf_page))
        elif re.search(r'\b\d{5}\b', line) and re.search(r'0\s*\.', line):
            raise ValueError(f'Unparsed row on PDF page {pdf_page}: {raw}')
    return result


def main():
    args = argparse.ArgumentParser()
    args.add_argument('pdf', type=Path)
    args.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'data' / 'municipios.js')
    args = args.parse_args()
    reader = PdfReader(args.pdf)
    records = []
    with pdfplumber.open(args.pdf) as other:
        for index in range(164, 186):
            primary = parse(reader.pages[index].extract_text(), index + 1)
            independent = parse(other.pages[index].extract_text(x_tolerance=2), index + 1)
            key = lambda row: (row['code'], row['aa'], row['av'], row['hazard'])
            if sorted(map(key, primary)) != sorted(map(key, independent)):
                raise ValueError(f'PDF reader mismatch on page {index + 1}')
            records.extend(primary)
    unique = {}
    for row in records:
        if row['code'] in unique:
            previous = unique[row['code']]
            assert all(previous[k] == row[k] for k in ('name', 'department', 'aa', 'av', 'hazard')), 'Conflicting duplicate'
            previous.setdefault('alsoPdfPages', []).append(row['pdfPage'])
        else:
            unique[row['code']] = row
    records = list(unique.values())
    assert len(set(row['department'] for row in records)) == 33
    assert len(records) > 1100
    for row in records:
        expected = 'Baja' if max(row['aa'], row['av']) <= .10 else 'Intermedia' if max(row['aa'], row['av']) <= .20 else 'Alta'
        assert row['hazard'] == expected, row
    records.sort(key=lambda row: (row['department'], row['name']))
    data = dict(source='NSR-10, Título A, Apéndice A-4',
                url='https://www.idrd.gov.co/sites/default/files/documentos/Construcciones/titulo-a-nsr-100.pdf',
                sourceSha256=hashlib.sha256(args.pdf.read_bytes()).hexdigest(),
                pdfPages=[165, 186], printedPages=['A-153', 'A-174'],
                count=len(records), departments=33,
                records=records)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('/* NSR-10, Appendix A-4. Generated by tools/extract_catalog.py. */\n'
                          'globalThis.NSR_CATALOG = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':'))
                          + ';\nif (typeof module !== "undefined" && module.exports) module.exports = globalThis.NSR_CATALOG;\n', encoding='utf-8')
    print(json.dumps(dict(count=len(records), departments=33, sha256=data['sourceSha256']), ensure_ascii=False))


if __name__ == '__main__':
    main()
